#!/usr/bin/env bash
# Regenerate control-domains.txt from the Cisco Umbrella top-1M domain
# ranking (https://s3-us-west-1.amazonaws.com/umbrella-static/top-1m.csv.zip).
#
# Umbrella ranks by real DNS resolution volume, which makes it the most
# representative public source for a synthetic DNS workload. The generated
# file is checked in and FROZEN after creation so latency comparisons stay
# reproducible; rerun this script only to deliberately cut a new corpus
# version, never to "refresh" the existing one.
#
# Usage:
#   scripts/benchmarks/corpus/fetch-top-domains.sh [COUNT] [OUTPUT]
#
#   COUNT   number of domains to keep, in rank order (default: 10000)
#   OUTPUT  corpus file to write (default: alongside this script)
#
# The on-disk format matches what the prober and dns53-benchmark.sh parse:
# one "<domain> [qtype]" per line, "#"-prefixed comments and blank lines
# ignored. Domains are written bare, so the qtype defaults to "A".

set -euo pipefail

COUNT="${1:-10000}"
OUTPUT="${2:-$(cd "$(dirname "$0")" && pwd)/control-domains.txt}"
SOURCE_URL="https://s3-us-west-1.amazonaws.com/umbrella-static/top-1m.csv.zip"

if ! [[ "$COUNT" =~ ^[0-9]+$ ]] || [ "$COUNT" -lt 1 ]; then
    echo "error: COUNT must be a positive integer, got '$COUNT'" >&2
    exit 1
fi

workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

echo "Downloading Umbrella top-1M from $SOURCE_URL ..." >&2
curl -fsSL "$SOURCE_URL" -o "$workdir/top-1m.csv.zip"

# Umbrella ships "rank,domain" CSV lines with no header row. Keep domains in
# rank order, lowercased, that look like syntactically valid DNS names (at
# least one dot, LDH labels), deduplicated, stopping at COUNT.
{
    echo "# PowerBlockade synthetic control corpus"
    echo "# Source: Cisco Umbrella top-1M ($(printf '%(%Y-%m-%d)T' -1) download), first $COUNT valid domains in rank order"
    echo "# Generated by: scripts/benchmarks/corpus/fetch-top-domains.sh $COUNT"
    echo "# DO NOT MODIFY - changes break historical latency comparisons."
    echo "# (This is the prober corpus; docs/performance/corpus/ holds the"
    echo "#  separate hand-curated benchmark set used by dns53-benchmark.sh.)"
    # Note: awk deliberately never exits early — an early exit closes the
    # pipe, SIGPIPEs unzip, and pipefail aborts the script.
    unzip -p "$workdir/top-1m.csv.zip" \
        | awk -v count="$COUNT" '
            {
                if (kept >= count) next
                sub(/\r$/, "") # Umbrella CSV ships CRLF; strip the CR
                n = split(tolower($0), f, ",")
                if (n < 2) next
                d = f[2]
                if (d !~ /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/) next
                if (seen[d]++) next
                print d
                kept++
            }'
} > "$OUTPUT"

# grep -c exits 1 when it counts zero matching lines; that is a data error
# caught below, not a script failure.
domains=$(grep -cve '^[[:space:]]*$' -e '^#' "$OUTPUT" || true)
if [ "$domains" -ne "$COUNT" ]; then
    echo "error: wrote $domains domains, expected $COUNT" >&2
    exit 1
fi

echo "Wrote $domains domains to $OUTPUT" >&2
